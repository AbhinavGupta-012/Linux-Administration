# Display all running processes using ps
ps aux

# Display only processes of the current user
ps -u $USER

# Monitor system processes dynamically using top
top -n 1

# Kill a process by PID
kill 364

# Installing software using apt-get
sudo apt-get install -y curl

# Updating package lists
sudo apt-get update

# Upgrading all installed packages
sudo apt-get upgrade -y

# Removing a package
sudo apt-get remove -y curl
